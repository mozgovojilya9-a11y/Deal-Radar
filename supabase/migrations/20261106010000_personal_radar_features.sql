-- Additive migration for user preferences, synced favorites, bot stats and price history.
-- Safe to run on the existing Deal Radar schema (uses listing_id from public.deals).
create table if not exists public.favorites (
  telegram_user_id bigint not null,
  deal_id text not null references public.deals(listing_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (telegram_user_id, deal_id)
);
create index if not exists favorites_user_created_idx
  on public.favorites (telegram_user_id, created_at desc);

create table if not exists public.user_settings (
  telegram_user_id bigint primary key,
  categories text[] not null default '{}',
  min_discount integer not null default 0 check (min_discount between 0 and 90),
  max_distance_km integer check (max_distance_km is null or max_distance_km between 1 and 500),
  updated_at timestamptz not null default now()
);

create table if not exists public.bot_status (
  id smallint primary key default 1 check (id = 1),
  last_run_at timestamptz not null default now(),
  last_run_found integer not null default 0,
  last_run_new integer not null default 0,
  last_run_errors integer not null default 0
);

alter table public.bot_status
  add column if not exists last_run_errors integer not null default 0;

create table if not exists public.deal_price_history (
  id bigint generated by default as identity primary key,
  listing_id text not null,
  price numeric(12,2) not null check (price > 0),
  market_price numeric(12,2),
  discount numeric(6,4),
  observed_at timestamptz not null default now()
);
create index if not exists deal_price_history_listing_time_idx
  on public.deal_price_history (listing_id, observed_at desc);

alter table public.favorites enable row level security;
alter table public.user_settings enable row level security;
alter table public.bot_status enable row level security;
alter table public.deal_price_history enable row level security;

revoke all on table public.favorites, public.user_settings, public.bot_status, public.deal_price_history from anon, authenticated;
grant all on table public.favorites, public.user_settings, public.bot_status, public.deal_price_history to service_role;
